/* =====================================================================
   DIAGNÓSTICO: RESPOSTAS ATRIBUÍDAS AO CURSO ERRADO
   ---------------------------------------------------------------------
   A consulta da CPA escolhe UMA matrícula por aluno (CROSS APPLY TOP 1,
   priorizando "Cursando"). Se o aluno tem duas matrículas no semestre
   (ex.: Teologia 2026/1T "Concluído" + um curso de extensão "Cursando"),
   a resposta vai para o curso de extensão e depois é filtrada.
   Rode as consultas A e B para confirmar. Contém RA: uso interno da CPA.
   ===================================================================== */

-- A. Outras matrículas no mesmo semestre dos alunos de Teologia 2026/1T
SELECT C.NOME AS CURSO, PLM.CODPERLET, ST.DESCRICAO AS STATUS, COUNT(DISTINCT M.RA) AS ALUNOS
FROM SMATRICPL M
INNER JOIN SPLETIVO PLM ON PLM.CODCOLIGADA = M.CODCOLIGADA AND PLM.IDPERLET = M.IDPERLET
                       AND PLM.CODFILIAL = M.CODFILIAL
INNER JOIN SSTATUS ST ON ST.CODCOLIGADA = M.CODCOLIGADA AND ST.CODSTATUS = M.CODSTATUS
LEFT JOIN SHABILITACAOFILIAL HF ON HF.CODCOLIGADA = M.CODCOLIGADA
                               AND HF.IDHABILITACAOFILIAL = M.IDHABILITACAOFILIAL
LEFT JOIN SCURSO C ON C.CODCOLIGADA = HF.CODCOLIGADA AND C.CODCURSO = HF.CODCURSO
WHERE M.CODCOLIGADA = 5
  AND LEFT(PLM.CODPERLET, 6) = '2026/1'
  AND M.RA IN (
        SELECT M2.RA
        FROM SMATRICPL M2
        INNER JOIN SPLETIVO P2 ON P2.CODCOLIGADA = M2.CODCOLIGADA AND P2.IDPERLET = M2.IDPERLET
                              AND P2.CODFILIAL = M2.CODFILIAL
        INNER JOIN SHABILITACAOFILIAL H2 ON H2.CODCOLIGADA = M2.CODCOLIGADA
                                        AND H2.IDHABILITACAOFILIAL = M2.IDHABILITACAOFILIAL
        INNER JOIN SCURSO C2 ON C2.CODCOLIGADA = H2.CODCOLIGADA AND C2.CODCURSO = H2.CODCURSO
        WHERE M2.CODCOLIGADA = 5 AND C2.NOME = 'Teologia' AND P2.CODPERLET = '2026/1T')
GROUP BY C.NOME, PLM.CODPERLET, ST.DESCRICAO
ORDER BY ALUNOS DESC;

-- B. Avaliações docentes desses alunos: em qual prova e de qual curso é a disciplina avaliada
SELECT P.CODPROVA, P.NOME AS PROVA, CD.NOME AS CURSO_DA_DISCIPLINA,
       COUNT(DISTINCT BH.ID) AS AVALIACOES, COUNT(DISTINCT BH.CODPESSOA) AS ALUNOS
FROM BHISTORICO BH
INNER JOIN BPROVA P ON P.CODCOLIGADA = BH.CODCOLIGADA AND P.CODPROVA = BH.CODPROVA
INNER JOIN BPERIODO PL ON PL.CODCOLIGADA = BH.CODCOLIGADA AND PL.CODPROVA = BH.CODPROVA
                      AND PL.CODPERIODO = BH.CODPERIODO
INNER JOIN SALUNO A ON A.CODCOLIGADA = BH.CODCOLIGADA AND A.CODPESSOA = BH.CODPESSOA
INNER JOIN SOBJETOAVALIADO SOA ON SOA.CODCOLIGADA = BH.CODCOLIGADA
                              AND SOA.SEQOBJETOAVALIADO = BH.SEQOBJETOAVALIADO
                              AND SOA.CODPROF IS NOT NULL AND SOA.IDTURMADISC IS NOT NULL
LEFT JOIN SMATRICULA MD ON MD.CODCOLIGADA = BH.CODCOLIGADA AND MD.RA = A.RA
                       AND MD.IDTURMADISC = SOA.IDTURMADISC
LEFT JOIN SHABILITACAOFILIAL HD ON HD.CODCOLIGADA = MD.CODCOLIGADA
                               AND HD.IDHABILITACAOFILIAL = MD.IDHABILITACAOFILIAL
LEFT JOIN SCURSO CD ON CD.CODCOLIGADA = HD.CODCOLIGADA AND CD.CODCURSO = HD.CODCURSO
WHERE BH.CODCOLIGADA = 5
  AND BH.CODAREA = '8'
  AND LEFT(PL.NOME, 6) = '2026/1'
  AND A.RA IN (
        SELECT M2.RA
        FROM SMATRICPL M2
        INNER JOIN SPLETIVO P2 ON P2.CODCOLIGADA = M2.CODCOLIGADA AND P2.IDPERLET = M2.IDPERLET
                              AND P2.CODFILIAL = M2.CODFILIAL
        INNER JOIN SHABILITACAOFILIAL H2 ON H2.CODCOLIGADA = M2.CODCOLIGADA
                                        AND H2.IDHABILITACAOFILIAL = M2.IDHABILITACAOFILIAL
        INNER JOIN SCURSO C2 ON C2.CODCOLIGADA = H2.CODCOLIGADA AND C2.CODCURSO = H2.CODCURSO
        WHERE M2.CODCOLIGADA = 5 AND C2.NOME = 'Teologia' AND P2.CODPERLET = '2026/1T')
GROUP BY P.CODPROVA, P.NOME, CD.NOME
ORDER BY AVALIACOES DESC;

